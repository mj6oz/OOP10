            this.dataGridView1.CellMouseDown += new System.Windows.Forms.DataGridViewCellMouseEventHandler(this.dataGridView1_CellMouseDown);
        }


        // Add to Wishlist Button Click Event
        private void button1_Click(object sender, EventArgs e)
        {
            // Requirement 1: Check if any fields are empty
            if (string.IsNullOrWhiteSpace(textBox1.Text) ||
                string.IsNullOrWhiteSpace(textBox2.Text) ||
                string.IsNullOrWhiteSpace(textBox3.Text) ||
                string.IsNullOrWhiteSpace(textBox4.Text))
            {
                MessageBox.Show("Please fill out all fields before submitting!", "Validation Error", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }


            // Requirement 1 & 2: Validate that Amount Range (textBox4) contains a valid numeric value
            if (!decimal.TryParse(textBox4.Text, out decimal decimalAmount))
            {
                MessageBox.Show("Please enter a valid numeric amount in the Amount Range field!", "Validation Error", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return; // Stop execution if letters or invalid formats were entered
            }


            // Requirement 2: Format the verified numeric amount into local currency standard ($0.00 format)
            string formattedAmount = decimalAmount.ToString("C");


            // Requirement 4: Add new row directly into DataGridView
            dataGridView1.Rows.Add(textBox1.Text, textBox2.Text, textBox3.Text, formattedAmount);


            // Requirement 3: Clear all textboxes
            textBox1.Clear();
            textBox2.Clear();
            textBox3.Clear();
            textBox4.Clear();
        }


        // Requirement 5: Right-click context menu and safe removal with popup confirmation
        private void dataGridView1_CellMouseDown(object sender, DataGridViewCellMouseEventArgs e)
        {
            // Ensure the user right-clicked valid row data (and not the column headers)
            if (e.Button == MouseButtons.Right && e.RowIndex >= 0)
            {
                // Clear existing selections and highlight targeted row
                dataGridView1.ClearSelection();
                dataGridView1.Rows[e.RowIndex].Selected = true;


                // Build floating right-click context menu
                ContextMenuStrip menu = new ContextMenuStrip();
                ToolStripMenuItem deleteItem = new ToolStripMenuItem("Delete Row");


                // Event triggered when user clicks "Delete Row"
                deleteItem.Click += (s, ev) =>
                {
                    // Prompt confirmation dialog before deleting
                    DialogResult result = MessageBox.Show(
                        "Are you sure you want to delete this item from your wishlist?",
                        "Confirm Deletion",
                        MessageBoxButtons.YesNo,
                        MessageBoxIcon.Question
                    );


                    // Process removal only if confirmed
                    if (result == DialogResult.Yes)
                    {
                        dataGridView1.Rows.RemoveAt(e.RowIndex);
                    }
                };


                menu.Items.Add(deleteItem);
                menu.Show(Cursor.Position);
            }
        }


